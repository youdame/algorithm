with max_colony as(SELECT YEAR(DIFFERENTIATION_DATE) as year, MAX(SIZE_OF_COLONY) as max_c
FROM ECOLI_DATA
GROUP BY YEAR(DIFFERENTIATION_DATE))


select year(DIFFERENTIATION_DATE) as year, M.max_c - e.SIZE_OF_COLONY as YEAR_DEV , ID
from ECOLI_DATA E
JOIN max_colony M
on year(DIFFERENTIATION_DATE) = m.year
order by year ,YEAR_DEV