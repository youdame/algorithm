WITH RECURSIVE TIME_TABLE as 
(SELECT 0 as HOUR
UNION ALL 
SELECT HOUR + 1 
 FROM TIME_TABLE
 WHERE HOUR < 23 
),
    
COUNT_TABLE AS 
(SELECT HOUR(DATETIME) as HOUR, COUNT(HOUR(DATETIME)) as COUNT
FROM ANIMAL_OUTS
GROUP BY HOUR
)


SELECT T.HOUR, IFNULL(C.COUNT, 0) as COUNT
FROM TIME_TABLE T
LEFT JOIN COUNT_TABLE C
ON T.HOUR = C.HOUR
ORDER BY T.HOUR